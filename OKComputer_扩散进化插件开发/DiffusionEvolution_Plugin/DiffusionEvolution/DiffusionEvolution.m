classdef DiffusionEvolution < ALGORITHM
% <2025> <multi> <real> <constrained/none>
% Diffusion Evolution - A hybrid algorithm combining diffusion models with evolutionary algorithms
% for multi-objective optimization
%
% This algorithm integrates diffusion models as intelligent mutation operators within the
% evolutionary framework. The diffusion model learns the distribution of current population
% and generates high-quality offspring to accelerate convergence.
%
%------------------------------- Parameters --------------------------------
% N              - Population size (default: 100)
% diffusion_steps- Number of diffusion steps (default: 1000)
% sample_size    - Number of samples generated by diffusion per generation (default: 50)
% hybrid_rate    - Proportion of diffusion-generated offspring (default: 0.3)
% model_type     - Type of diffusion model ('DDPM' or 'DDIM') (default: 'DDPM')
% training_epochs- Epochs for training diffusion model per generation (default: 10)
% noise_schedule - Noise schedule type ('linear' or 'cosine') (default: 'linear')
% condition_type - Condition type for diffusion ('none', 'fitness', 'rank') (default: 'fitness')
%
%------------------------------- Reference --------------------------------
% Inspired by diffusion models in deep learning and evolutionary computation.
% This implementation combines the strengths of both approaches for multi-objective optimization.
%
%------------------------------- Copyright --------------------------------
